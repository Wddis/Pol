#!/usr/bin/env python3
"""Generates src/syscalls_compat.h (32-bit syscall numbers) from the kernel UAPI headers:
ARM EABI from the Android NDK sysroot, i386 from the host's linux headers. Run when updating."""
import re, sys, pathlib

NAMES = """openat fstatat64 statx faccessat faccessat2 mkdirat mknodat unlinkat fchmodat utimensat chdir truncate truncate64
statfs statfs64 getxattr lgetxattr setxattr lsetxattr listxattr llistxattr removexattr lremovexattr inotify_add_watch
renameat renameat2 linkat symlinkat readlinkat execve getcwd connect bind fchownat fchown32 open creat stat64 lstat64
access mkdir rmdir unlink chmod mknod utimes rename link symlink readlink chown32 lchown32 getuid32 geteuid32 getgid32
getegid32 setuid32 setgid32 setreuid32 setregid32 setresuid32 setresgid32 getresuid32 getresgid32 setfsuid32 setfsgid32
setgroups32 mount umount2 pivot_root chroot sethostname setdomainname swapon swapoff acct reboot unshare setns init_module
finit_module delete_module capget capset prctl getpid gettid getppid kill tkill tgkill getsockname getpeername accept accept4 setrlimit prlimit64 bpf""".split()

def parse(path):
    nums = {}
    for line in pathlib.Path(path).read_text().splitlines():
        m = re.match(r'#define __NR_(\w+)\s+\(?(?:__NR_SYSCALL_BASE\s*\+\s*)?(\d+)\)?', line)
        if m: nums[m.group(1)] = int(m.group(2))
    return nums

def emit(ns, nums):
    out = [f"namespace {ns} {{"]
    for n in NAMES:
        v = nums.get(n, -1)
        out.append(f"constexpr long {n} = {v};")
    out.append(f"}}  // namespace {ns}")
    return "\n".join(out)

arm = parse(sys.argv[1])
x86 = parse(sys.argv[2])
hdr = ["// Generated by tools/gen_compat_syscalls.py from kernel UAPI headers. Do not edit.",
       "// -1 = the syscall does not exist on that ABI.", "// SPDX-License-Identifier: Apache-2.0",
       "#pragma once", "", "namespace nest::sys32 {", emit("arm", arm), "", emit("i386", x86), "}  // namespace nest::sys32", ""]
pathlib.Path(sys.argv[3]).write_text("\n".join(hdr))
print("arm", sum(1 for n in NAMES if n in arm), "/", len(NAMES), " i386", sum(1 for n in NAMES if n in x86))
